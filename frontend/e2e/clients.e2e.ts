// Clients (docs/57), on the plain server and the database e2e/console_server.py seeded for this
// run: the platform owner lands on Clients (the platform's health, one row per organization),
// opens a client (metrics only, said in a banner, nothing to change) and one application over
// time, in both windows; every other role is refused each Clients address with one sentence and
// no request for it, and each of the four routes answers it the same 403 bytes; the Clients
// chunk loads on demand from this origin, blocking nothing; by keyboard alone; at a phone's
// width; each state pictured and checked by axe in both themes; the leak scan at the end of each
// test. The passwords were generated by playwright.config.ts.

import { expect, test, type Browser, type Page, type TestInfo } from "@playwright/test";
import {
  ADMIN,
  ALL,
  NO_ROLE,
  NOT_AVAILABLE,
  OPERATOR,
  SESSION_ENDED,
  ORG_READER,
  APP_ADMIN,
  APP_READER,
  type Account,
  Scan,
  logIn,
  picture,
  sections,
} from "./session";

test.describe.configure({ mode: "serial" });

const FORBIDDEN = '{"error":{"code":"forbidden","message":"Not permitted, or not found."}}';
const ROUTES = [
  "/v1/admin/orgs",
  "/v1/admin/platform/usage",
  "/v1/admin/platform/orgs/acme/applications/metrics",
  "/v1/admin/platform/orgs/acme/applications/app-one/metrics",
];
// Missing and misplaced: refused as forbidden ones, for the platform owner too.
const MISSING = [
  "/v1/admin/platform/orgs/nowhere/applications/metrics",
  "/v1/admin/platform/orgs/acme/applications/ghost/metrics",
  "/v1/admin/platform/orgs/default/applications/app-one/metrics",
];

/** The JavaScript files the page has fetched, by name. */
function scripts(requests: string[]): string[] {
  return requests
    .filter((url) => url.endsWith(".js"))
    .map((url) => new URL(url).pathname.split("/").pop() ?? "");
}

async function watchPolicy(page: Page): Promise<() => Promise<string[]>> {
  await page.addInitScript(() => {
    const seen: string[] = [];
    Object.assign(window, { policyViolations: seen });
    document.addEventListener("securitypolicyviolation", (event) => {
      seen.push(`${event.violatedDirective} ${event.blockedURI}`);
    });
  });
  return () =>
    page.evaluate(() => (window as unknown as { policyViolations: string[] }).policyViolations);
}

function clients(page: Page) {
  return page.getByRole("region", { name: "Clients", exact: true });
}

async function drawn(page: Page): Promise<void> {
  await expect(page.locator(".skeleton")).toHaveCount(0);
}

test("the platform owner lands on Clients, opens a client and one application, in both windows; the chunk loads on demand", async ({
  page,
}, testInfo) => {
  const scan = new Scan();
  scan.watch(page);
  const violations = await watchPolicy(page);
  await page.goto("/dashboard/");
  await expect(page.getByRole("region", { name: "Log in", exact: true })).toBeVisible();
  expect(scripts(scan.requests).some((name) => name.startsWith("ClientsScreen-"))).toBe(false);
  await logIn(page, OPERATOR, scan);

  // The landing: the platform's health, then one row per organization.
  await expect(clients(page)).toBeVisible();
  expect(scripts(scan.requests).some((name) => name.startsWith("ClientsScreen-"))).toBe(true);
  await expect(sections(page).getByRole("link", { name: "Clients", exact: true })).toBeVisible();
  const health = clients(page).getByRole("region", { name: "Platform", exact: true });
  await expect(health).toContainText("Alert evaluator");
  await expect(health).toContainText("Stores");
  await expect(clients(page)).toContainText("Platform settings are environment variables");
  const table = clients(page).getByRole("table", { name: "Clients" });
  await expect(table.getByRole("link", { name: "Acme Corp" })).toBeVisible();
  // In-memory counts: the window says since the gateway restarted.
  await expect(clients(page)).toContainText("when the gateway restarted");
  await drawn(page);
  await picture(page, testInfo, "clients-platform-admin");

  await clients(page).getByRole("button", { name: "last 24 hours" }).click();
  await expect(clients(page).getByRole("button", { name: "last 24 hours" })).toHaveAttribute(
    "aria-pressed",
    "true",
  );
  await expect(clients(page)).toContainText("not a whole 24 hours");
  await drawn(page);
  await picture(page, testInfo, "clients-24h-platform-admin");

  // One client: the banner, its applications, nothing to change.
  await clients(page).getByRole("button", { name: "last 60 minutes" }).click();
  await table.getByRole("link", { name: "Acme Corp" }).click();
  const client = page.getByRole("region", { name: "acme", exact: true });
  await expect(client.getByRole("note")).toHaveText("Viewing as platform owner: metrics only");
  const apps = client.getByRole("table", { name: "Applications" });
  await expect(apps.getByRole("link", { name: "App one" })).toBeVisible();
  const hrefs = await client
    .getByRole("link")
    .evaluateAll((links) => links.map((link) => link.getAttribute("href")));
  expect(hrefs.every((href) => href?.startsWith("#/clients/acme/"))).toBe(true);
  await expect(client.getByRole("textbox")).toHaveCount(0);
  await expect(client.getByRole("checkbox")).toHaveCount(0);
  await drawn(page);
  await picture(page, testInfo, "client-platform-admin");

  // One application over time, each minute, then each hour.
  await apps.getByRole("link", { name: "App one" }).click();
  const one = page.getByRole("region", { name: "acme / app-one", exact: true });
  await expect(one.getByRole("table", { name: "App one, each minute" })).toBeVisible();
  expect(new URL(page.url()).hash).toBe("#/clients/acme/app-one");
  await drawn(page);
  await picture(page, testInfo, "client-application-platform-admin");
  await one.getByRole("button", { name: "last 24 hours" }).click();
  await expect(one.getByRole("table", { name: "App one, each hour" })).toBeVisible();
  await drawn(page);
  await picture(page, testInfo, "client-application-24h-platform-admin");

  // The breadcrumb goes back to Clients.
  await page
    .getByRole("navigation", { name: "Breadcrumb" })
    .getByRole("link", { name: "Clients" })
    .click();
  await expect(clients(page)).toBeVisible();

  // Each route answers it; missing and misplaced answer the forbidden bytes.
  for (const path of ROUTES) expect((await page.request.get(path)).status(), path).toBe(200);
  for (const path of MISSING) {
    const answer = await page.request.get(path);
    expect([answer.status(), await answer.text()], path).toEqual([403, FORBIDDEN]);
  }
  expect(await violations()).toEqual([]);
  const origin = new URL(page.url()).origin;
  expect(
    scan.requests.filter((url) => !url.startsWith(origin) && !url.startsWith("data:")),
  ).toEqual([]);
  expect(await scan.leaks(page)).toEqual([]);
});

const OTHERS: [Account, string, string][] = [
  [ADMIN, "org-admin", "Applications"],
  [ORG_READER, "organization-reader", "Applications"],
  [APP_ADMIN, "app-admin", "App one"],
  [APP_READER, "application-reader", "App one"],
  [NO_ROLE, "no-role", "Home"],
];

for (const [who, name, landing] of OTHERS) {
  test(`${name}: no Clients; each Clients address refused with no request; each route the same 403 bytes`, async ({
    page,
  }, testInfo) => {
    const scan = new Scan();
    scan.watch(page);
    await page.goto("/dashboard/");
    await logIn(page, who, scan);
    await expect(sections(page).getByRole("link", { name: "Clients" })).toHaveCount(0);
    for (const hash of ["#/clients", "#/clients/acme", "#/clients/acme/app-one"]) {
      await page.goto(`/dashboard/${hash}`);
      await expect(
        page.getByRole("region", { name: landing, exact: true }).getByRole("alert").first(),
      ).toHaveText(NOT_AVAILABLE);
      await scan.step(page);
    }
    expect(scan.requests.some((url) => url.includes("/v1/admin/platform/"))).toBe(false);
    expect(scan.requests.some((url) => /\/v1\/admin\/orgs(\?|$)/.test(url))).toBe(false);
    expect(scripts(scan.requests).some((file) => file.startsWith("ClientsScreen-"))).toBe(false);
    for (const path of [...ROUTES, ...MISSING]) {
      const answer = await page.request.get(path);
      expect([answer.status(), await answer.text()], path).toEqual([403, FORBIDDEN]);
    }
    await picture(page, testInfo, `clients-refused-${name}`);
    expect(await scan.leaks(page)).toEqual([]);
  });
}

test("by keyboard alone: from Clients to a client and back", async ({ page }) => {
  const scan = new Scan();
  scan.watch(page);
  await page.goto("/dashboard/");
  await logIn(page, OPERATOR, scan);
  const link = clients(page).getByRole("table", { name: "Clients" }).getByRole("link", {
    name: "Acme Corp",
  });
  await expect(link).toBeVisible();
  for (let presses = 0; presses < 40; presses += 1) {
    if (await link.evaluate((element) => element === document.activeElement)) break;
    await page.keyboard.press("Tab");
  }
  await expect(link).toBeFocused();
  await page.keyboard.press("Enter");
  const client = page.getByRole("region", { name: "acme", exact: true });
  await expect(client.getByRole("note")).toBeVisible();
  const day = client.getByRole("button", { name: "last 24 hours" });
  for (let presses = 0; presses < 40; presses += 1) {
    if (await day.evaluate((element) => element === document.activeElement)) break;
    await page.keyboard.press("Tab");
  }
  await expect(day).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(day).toHaveAttribute("aria-pressed", "true");
  expect(await scan.leaks(page)).toEqual([]);
});

test("a phone: Clients, a client and one application at 390 px, both themes, under axe", async ({
  page,
}, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/dashboard/");
  await logIn(page, OPERATOR);
  const narrow = async (slug: string) => {
    await drawn(page);
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth),
    ).toBeLessThanOrEqual(0);
    await picture(page, testInfo, `phone-${slug}`);
  };
  await expect(clients(page).getByRole("table", { name: "Clients" })).toBeVisible();
  await narrow("clients");
  await page.goto("/dashboard/#/clients/acme");
  await expect(
    page.getByRole("region", { name: "acme", exact: true }).getByRole("note"),
  ).toBeVisible();
  await expect(page.getByRole("table", { name: "Applications" })).toBeVisible();
  await narrow("client");
  await page.goto("/dashboard/#/clients/acme/app-one");
  await expect(page.getByRole("table", { name: "App one, each minute" })).toBeVisible();
  await narrow("client-application");
});

async function freshPage(browser: Browser, testInfo: TestInfo): Promise<Page> {
  const context = await browser.newContext({
    baseURL: testInfo.project.use.baseURL,
    viewport: { width: 1400, height: 1000 },
  });
  return context.newPage();
}

/** Ends the page's session from another browser holding the same cookie. */
async function endSessionElsewhere(page: Page, browser: Browser, testInfo: TestInfo) {
  const session = (await page.context().cookies()).find((c) => c.name === "gw_session");
  expect(session).toBeDefined();
  const other = await browser.newContext({ baseURL: testInfo.project.use.baseURL });
  if (session !== undefined) await other.addCookies([session]);
  const me = (await (await other.request.get("/v1/auth/me")).json()) as { csrf_token: string };
  const out = await other.request.post("/v1/auth/logout", {
    headers: { "X-CSRF-Token": me.csrf_token },
    data: {},
  });
  expect(out.status()).toBe(200);
  await other.close();
}

test("a deep link to a client from logged out opens it after login", async ({
  browser,
}, testInfo) => {
  const page = await freshPage(browser, testInfo);
  const scan = new Scan();
  scan.watch(page);
  await page.goto("/dashboard/#/clients/acme/app-one");
  await expect(page.getByRole("region", { name: "Log in", exact: true })).toBeVisible();
  await logIn(page, OPERATOR, scan);
  await expect(page.getByRole("table", { name: "App one, each minute" })).toBeVisible();
  expect(new URL(page.url()).hash).toBe("#/clients/acme/app-one");
  expect(await scan.leaks(page)).toEqual([]);
  await page.context().close();
});

test("a session ended on Clients sends the page to login where it was", async ({
  browser,
}, testInfo) => {
  const page = await freshPage(browser, testInfo);
  const scan = new Scan();
  scan.watch(page);
  await page.goto("/dashboard/#/clients");
  await logIn(page, OPERATOR, scan);
  await expect(clients(page).getByRole("table", { name: "Clients" })).toBeVisible();
  await endSessionElsewhere(page, browser, testInfo);
  // The next read (the other window) is answered 401: the login, with the notice, the hash kept.
  await clients(page).getByRole("button", { name: "last 24 hours" }).click();
  const login = page.getByRole("region", { name: "Log in", exact: true });
  await expect(login).toBeVisible();
  await expect(login).toContainText(SESSION_ENDED);
  expect(new URL(page.url()).hash).toBe("#/clients");
  expect(await scan.leaks(page)).toEqual([]);
  await page.context().close();
});

test("every account in this run was asked: the list of roles is the run's", () => {
  expect(new Set([OPERATOR, ...OTHERS.map(([who]) => who)])).toEqual(new Set(ALL));
});
